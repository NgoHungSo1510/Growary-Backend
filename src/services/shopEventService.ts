/**
 * Tính toán giá sau khi áp dụng Flash Sale và chiết khấu VIP.
 * @param pointCost - Giá gốc của sản phẩm tính bằng Coins
 * @param userVipTier - Hạng VIP hiện tại của người dùng (0 - 11)
 * @param activeEvent - Sự kiện Flash Sale đang kích hoạt (nếu có)
 * @param targetRewardId - ID của sản phẩm để kiểm tra áp dụng giảm giá riêng
 * @returns Giá bán cuối cùng (tối thiểu 1 coin)
 */
export function calculateDiscountedPrice(
    pointCost: number,
    userVipTier: number,
    activeEvent: IShopEvent | null,
    targetRewardId?: string
): number {
    if (!activeEvent || activeEvent.type !== 'flash_sale' || !activeEvent.isActive) {
        return pointCost;
    }

    // Kiểm tra targetRewards nếu có chỉ định cụ thể
    if (activeEvent.targetRewards && activeEvent.targetRewards.length > 0 && targetRewardId) {
        const isTargeted = activeEvent.targetRewards.some(
            (id) => id.toString() === targetRewardId.toString()
        );
        if (!isTargeted) {
            return pointCost;
        }
    }

    // Áp dụng % giảm giá Flash Sale
    const discount = Math.min(100, Math.max(0, activeEvent.discountPercent));
    const salePrice = Math.ceil(pointCost * (1 - discount / 100));

    return Math.max(1, salePrice);
}

/**
 * Lấy sự kiện Flash Sale đang diễn ra trong thời điểm hiện tại.
 * @returns Bản ghi ShopEvent đang active hoặc null nếu không có
 */
export async function getActiveFlashSale(): Promise<IShopEvent | null> {
    const now = new Date();
    return ShopEvent.findOne({
        type: 'flash_sale',
        isActive: true,
        startDate: { $lte: now },
        endDate: { $gt: now },
    });
}

/**
 * Lấy danh sách tất cả các sự kiện Shop (dành cho quản trị Admin).
 * @param filter - Bộ lọc trạng thái ('active', 'done', 'auto', 'all')
 * @returns Danh sách ShopEvent
 */
export async function getAllShopEvents(filter?: string): Promise<IShopEvent[]> {
    const query: Record<string, unknown> = {};
    const now = new Date();

    if (filter === 'active') {
        query.isActive = true;
        query.endDate = { $gt: now };
    } else if (filter === 'done') {
        query.endDate = { $lte: now };
    } else if (filter === 'auto') {
        query.isAutoGenerated = true;
    }

    return ShopEvent.find(query).sort({ createdAt: -1 });
}

/**
 * Tạo sự kiện Shop thủ công từ trang quản trị Admin.
 * @param data - DTO thông tin sự kiện
 * @param adminId - ID của Admin thực hiện tạo
 * @returns Bản ghi ShopEvent vừa tạo
 */
export async function createAdminEvent(
    data: CreateShopEventDto,
    adminId?: string
): Promise<IShopEvent> {
    const event = new ShopEvent({
        ...data,
        isAutoGenerated: false,
        createdBy: adminId,
    });
    return event.save();
}

/**
 * Cập nhật cấu hình hoặc trạng thái bật/tắt của sự kiện.
 * @param id - ID của ShopEvent cần sửa
 * @param data - Dữ liệu cập nhật
 * @returns Bản ghi ShopEvent sau cập nhật hoặc null nếu không tìm thấy
 */
export async function updateShopEvent(
    id: string,
    data: Partial<IShopEvent>
): Promise<IShopEvent | null> {
    return ShopEvent.findByIdAndUpdate(id, { $set: data }, { new: true });
}

/**
 * Xóa sự kiện Shop (chỉ cho phép xóa sự kiện chưa bắt đầu).
 * @param id - ID sự kiện cần xóa
 * @returns True nếu xóa thành công, False nếu sự kiện đã/đang chạy
 */
export async function deleteShopEvent(id: string): Promise<boolean> {
    const event = await ShopEvent.findById(id);
    if (!event) return false;

    // Chỉ xóa được sự kiện chưa bắt đầu
    if (new Date(event.startDate) <= new Date()) {
        throw new Error('Chỉ có thể xóa sự kiện chưa bắt đầu');
    }

    await ShopEvent.findByIdAndDelete(id);
    return true;
}

/**
 * Tạo sự kiện Flash Sale tự động ngẫu nhiên hàng ngày (dành cho Cron Job).
 * @returns Bản ghi ShopEvent mới nếu kích hoạt thành công, null nếu bỏ qua
 */
export async function createDailyAutoFlashSale(): Promise<IShopEvent | null> {
    const now = new Date();
    const startOfMonth = new Date(now.getFullYear(), now.getMonth(), 1);

    // Kiểm tra xem trong tháng này đã có auto event nào chưa (mỗi tháng tối đa 1 lần)
    const existingAuto = await ShopEvent.findOne({
        isAutoGenerated: true,
        createdAt: { $gte: startOfMonth },
    });

    if (existingAuto) {
        return null;
    }

    // 10% xác suất xuất hiện mỗi ngày
    const roll = Math.random();
    if (roll >= 0.10) {
        return null;
    }

    // Random template thông điệp thương nhân
    const templateIndex = Math.floor(Math.random() * MERCHANT_MESSAGES.length);
    const template = MERCHANT_MESSAGES[templateIndex];

    // Random giảm giá từ 5% đến 20%
    const discountPercent = Math.floor(Math.random() * 16) + 5;
    const endDate = new Date(now.getTime() + 24 * 3600 * 1000);

    const newEvent = new ShopEvent({
        title: template.title,
        description: template.description,
        type: 'flash_sale',
        discountPercent,
        startDate: now,
        endDate,
        isActive: true,
        isAutoGenerated: true,
    });

    const saved = await newEvent.save();

    // Broadcast in-app notification cho user
    try {
        await Notification.create({
            title: `⚡ ${template.title}`,
            message: `${template.description} (Giảm ${discountPercent}% trong 24h)`,
            type: 'announcement',
            isRead: false,
        });
    } catch {
        // Notification failure does not rollback event creation
    }

    return saved;
}
