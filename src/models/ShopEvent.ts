import mongoose, { Schema, Document, Types } from 'mongoose';
import { ShopEventType } from '@shared';

export interface IShopEvent extends Document {
    title: string;
    description: string;
    type: ShopEventType;
    discountPercent: number;
    minVipTier?: number;
    targetRewards?: Types.ObjectId[];
    startDate: Date;
    endDate: Date;
    isActive: boolean;
    isAutoGenerated: boolean;
    createdBy?: Types.ObjectId;
    createdAt: Date;
    updatedAt: Date;
}

const shopEventSchema = new Schema<IShopEvent>(
    {
        title: {
            type: String,
            required: [true, 'Tiêu đề sự kiện là bắt buộc'],
            trim: true,
        },
        description: {
            type: String,
            required: [true, 'Mô tả sự kiện là bắt buộc'],
            trim: true,
        },
        type: {
            type: String,
            required: true,
            enum: [
                'flash_sale',
                'double_cashback',
                'lucky_purchase',
                'vip_exclusive',
                'fragment_exchange',
                'free_ship_day',
            ],
            default: 'flash_sale',
        },
        discountPercent: {
            type: Number,
            required: true,
            min: 0,
            max: 100,
            default: 10,
        },
        minVipTier: {
            type: Number,
            min: 0,
            max: 11,
            default: 0,
        },
        targetRewards: [
            {
                type: Schema.Types.ObjectId,
                ref: 'Reward',
            },
        ],
        startDate: {
            type: Date,
            required: true,
        },
        endDate: {
            type: Date,
            required: true,
        },
        isActive: {
            type: Boolean,
            default: true,
            index: true,
        },
        isAutoGenerated: {
            type: Boolean,
            default: false,
        },
        createdBy: {
            type: Schema.Types.ObjectId,
            ref: 'User',
        },
    },
    {
        timestamps: true,
    }
);

// Compound indexes for fast active event queries
shopEventSchema.index({ type: 1, isActive: 1, endDate: 1 });
shopEventSchema.index({ startDate: 1, endDate: 1 });
shopEventSchema.index({ createdAt: -1 });

export const ShopEvent = mongoose.model<IShopEvent>('ShopEvent', shopEventSchema);
