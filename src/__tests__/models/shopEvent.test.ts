import mongoose from 'mongoose';
import { ShopEvent, IShopEvent } from '../../models/ShopEvent';
import { SpecialItemConfig, ISpecialItemConfig } from '../../models/SpecialItemConfig';

describe('ShopEvent and SpecialItemConfig Models', () => {
    describe('ShopEvent Model', () => {
        it('should validate a valid flash_sale event', () => {
            const eventData = {
                title: 'Thương Nhân Kỳ Lạ',
                description: 'Giảm giá 15% trong 24 giờ',
                type: 'flash_sale',
                discountPercent: 15,
                startDate: new Date(),
                endDate: new Date(Date.now() + 24 * 3600 * 1000),
                isActive: true,
                isAutoGenerated: false,
            };

            const event = new ShopEvent(eventData);
            const err = event.validateSync();
            expect(err).toBeUndefined();
            expect(event.title).toBe(eventData.title);
            expect(event.type).toBe('flash_sale');
            expect(event.discountPercent).toBe(15);
        });

        it('should fail validation when required fields are missing', () => {
            const event = new ShopEvent({});
            const err = event.validateSync();
            expect(err).toBeDefined();
            expect(err?.errors.title).toBeDefined();
            expect(err?.errors.startDate).toBeDefined();
            expect(err?.errors.endDate).toBeDefined();
        });

        it('should have compound indexes defined', () => {
            const indexes = ShopEvent.schema.indexes();
            const hasTypeActiveEndIndex = indexes.some(
                ([fields]: [Record<string, unknown>, unknown]) =>
                    fields.type === 1 && fields.isActive === 1 && fields.endDate === 1
            );
            expect(hasTypeActiveEndIndex).toBe(true);
        });
    });

    describe('SpecialItemConfig Model', () => {
        it('should validate a valid product-fragment mapping', () => {
            const configData = {
                reward: new mongoose.Types.ObjectId(),
                fragmentType: 'frag_3k',
                isActive: true,
                addedToBoxPool: false,
            };

            const config = new SpecialItemConfig(configData);
            const err = config.validateSync();
            expect(err).toBeUndefined();
            expect(config.fragmentType).toBe('frag_3k');
        });

        it('should fail validation when reward or fragmentType is missing', () => {
            const config = new SpecialItemConfig({});
            const err = config.validateSync();
            expect(err).toBeDefined();
            expect(err?.errors.reward).toBeDefined();
            expect(err?.errors.fragmentType).toBeDefined();
        });
    });
});
