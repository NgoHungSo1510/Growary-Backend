import { processDailyFlashSaleCheck } from '../../jobs/shopEventJob';
import * as shopEventService from '../../services/shopEventService';

jest.mock('../../services/shopEventService', () => ({
    createDailyAutoFlashSale: jest.fn(),
}));

describe('shopEventJob', () => {
    beforeEach(() => {
        jest.clearAllMocks();
    });

    it('should call createDailyAutoFlashSale and return created event when triggered', async () => {
        const mockCreated = {
            _id: '507f1f77bcf86cd799439011',
            title: 'Thương Nhân Thời Không',
            discountPercent: 12,
            isAutoGenerated: true,
        };

        (shopEventService.createDailyAutoFlashSale as jest.Mock).mockResolvedValueOnce(mockCreated);

        const result = await processDailyFlashSaleCheck();
        expect(shopEventService.createDailyAutoFlashSale).toHaveBeenCalledTimes(1);
        expect(result).toEqual(mockCreated);
    });

    it('should return null when no event is rolled or monthly limit reached', async () => {
        (shopEventService.createDailyAutoFlashSale as jest.Mock).mockResolvedValueOnce(null);

        const result = await processDailyFlashSaleCheck();
        expect(shopEventService.createDailyAutoFlashSale).toHaveBeenCalledTimes(1);
        expect(result).toBeNull();
    });
});
